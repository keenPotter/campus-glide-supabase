-- Keeps the vehicle's own maintenance dates in sync, but only when this log is the vehicle's latest one.
create function private.sync_vehicle_maintenance_dates() returns trigger
language plpgsql security definer set search_path = public as $$
declare
    v_latest bigint;
begin
    select id into v_latest
    from vehicle_maintenance
    where vehicle_id = new.vehicle_id
    order by maintenance_date desc, id desc
    limit 1;

    if v_latest = new.id then
        update vehicles
        set last_maintenance_date = new.maintenance_date,
            next_maintenance_date = new.next_due_date
        where id = new.vehicle_id;
    end if;

    return new;
end $$;

create trigger trg_sync_vehicle_dates
    after insert or update on public.vehicle_maintenance
    for each row execute function private.sync_vehicle_maintenance_dates();

