-- Faculty can only create requests for today or later (checked only for API users, not for seeds).
create function private.validate_vehicle_request() returns trigger
language plpgsql security definer set search_path = public, private as $$
begin
    if auth.uid() is not null and new.trip_date < private.ph_today() then
        raise exception 'The trip date must be today or a later date.'
            using errcode = 'PT422',
                  detail = jsonb_build_object('errors',
                           jsonb_build_object('trip_date', jsonb_build_array('The trip date must be today or a later date.')))::text;
    end if;
    return new;
end $$;

create trigger trg_validate_vehicle_request
    before insert on public.vehicle_requests
    for each row execute function private.validate_vehicle_request();

