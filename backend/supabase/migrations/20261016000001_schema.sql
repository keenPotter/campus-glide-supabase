-- Schema for the Supabase version of CampusGlide (replaces all Laravel migrations).

create schema if not exists private;   -- not exposed through the API

create domain public.condition_rating as text
    check (value in ('excellent', 'good', 'poor'));

create function private.set_updated_at() returns trigger
language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end $$;

-- The app runs on Asia/Manila time (see config/app.php in the Laravel version).
create function private.ph_now() returns timestamp
language sql stable as $$ select now() at time zone 'Asia/Manila' $$;

create function private.ph_today() returns date
language sql stable as $$ select (now() at time zone 'Asia/Manila')::date $$;

-- ---------------------------------------------------------------- profiles
-- One row per auth user. Replaces the Laravel `users` table.
create table public.profiles (
    id           uuid primary key references auth.users (id) on delete cascade,
    email        text not null unique,
    first_name   text not null,
    last_name    text not null,
    full_name    text generated always as (trim(first_name || ' ' || last_name)) stored,
    position     text,
    phone_number text,
    role         text not null check (role in ('administrator', 'faculty')),
    is_active    boolean not null default true,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);

-- Creates the profile when an account is created (by the register-user function).
-- IMPORTANT: turn OFF public sign-ups (Auth > Providers > Email), because the role
-- comes from the user metadata.
create function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
    insert into public.profiles (id, email, first_name, last_name, position, phone_number, role)
    values (
        new.id,
        new.email,
        coalesce(new.raw_user_meta_data ->> 'first_name', ''),
        coalesce(new.raw_user_meta_data ->> 'last_name', ''),
        new.raw_user_meta_data ->> 'position',
        new.raw_user_meta_data ->> 'phone_number',
        coalesce(new.raw_user_meta_data ->> 'role', 'faculty')
    );
    return new;
end $$;

create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function private.handle_new_user();

